const FORBIDDEN_SYSTEM_WORDS = ['완치', '100%', '최고', '특효', '예약', '내원', '상담 신청', '문의하세요', '한약 처방'];

function auditAnatomySystemsData() {
  const errors = [];
  for (const tab of ANATOMY_SYSTEM_TABS) {
    const sysMap = ANATOMY_SYSTEMS_CONTENT[tab.id];
    if (!sysMap) {
      errors.push('Missing system map: ' + tab.id);
      continue;
    }
    for (const reg of ANATOMY_REGIONS_META) {
      const item = sysMap[reg.id];
      if (!item) {
        errors.push(`Missing region ${tab.id}.${reg.id}`);
        continue;
      }
      if (!item.structures || !item.role || !item.pain || !item.exercise) {
        errors.push(`Incomplete fields in ${tab.id}.${reg.id}`);
      }
      const joined = [item.structures, item.role, item.pain, item.exercise].join(' ');
      for (const w of FORBIDDEN_SYSTEM_WORDS) {
        if (joined.includes(w)) {
          errors.push(`Forbidden word "${w}" in ${tab.id}.${reg.id}`);
        }
      }
    }
  }
  return { passed: errors.length === 0, errors };
}

module.exports = {
  ANATOMY_SYSTEM_TABS,
  ANATOMY_REGIONS_META,
  ANATOMY_SYSTEMS_CONTENT,
  auditAnatomySystemsData
};
