/**
 * 약관 모달 오픈 및 렌더링 함수
 */
function openTermsModal(type) {
  const modal = document.getElementById('terms-modal');
  const titleEl = document.getElementById('terms-modal-title');
  const subtitleEl = document.getElementById('terms-modal-subtitle');
  const bodyEl = document.getElementById('terms-modal-body');

  const data = BAREUN_TERMS_DATA[type] || BAREUN_TERMS_DATA.service;

  if (titleEl) titleEl.textContent = data.title;
  if (subtitleEl) subtitleEl.textContent = data.subtitle;
  if (bodyEl) bodyEl.innerHTML = data.content;

  if (modal) {
    modal.classList.add('active');
    document.body.style.overflow = 'hidden';
  }
}

function closeTermsModal() {
  const modal = document.getElementById('terms-modal');
  if (modal) {
    modal.classList.remove('active');
    document.body.style.overflow = '';
  }
}

// Esc Key 및 백드롭 클릭 지원
window.addEventListener('keydown', (e) => {
  if (e.key === 'Escape') closeTermsModal();
});
